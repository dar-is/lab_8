#include <stdio.h>

int main(void)
{
    double a = 2.0, b = 4.0;    // границы интервала
    double h;                   // шаг табуляции

    // п.1: приглашение к вводу содержит вычисляемую функцию
    printf("Табулирование функции y = x^3 + 3x^2 - 3 на [%.0f; %.0f]\n", a, b);
    printf("Введите шаг табуляции h: ");

    // п.2: ввод шага
    if (scanf("%lf", &h) != 1 || h <= 0)
    {
        printf("Ошибка: шаг должен быть положительным числом.\n");
        return 1;
    }

    // п.3: вывод таблицы
    printf("\n+------------+------------+\n");
    printf("|     x      |    f(x)    |\n");
    printf("+------------+------------+\n");

    // счётчик k нужен, чтобы не накапливать ошибку сложения вещественных чисел
    for (int k = 0; a + k * h <= b + 1e-9; k++)
    {
        double x = a + k * h;
        double y = x * x * x + 3 * x * x - 3;
        printf("| %10.4f | %10.4f |\n", x, y);
    }

    printf("+------------+------------+\n");
    return 0;
}
